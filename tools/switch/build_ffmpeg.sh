#!/bin/sh
# Builds the FFmpeg the Switch port links: static libavformat, libavcodec,
# libswscale, libswresample and libavutil for devkitA64 (Nintendo Switch
# homebrew), with the same decoder-only, LGPL configuration as the Android
# build (tools/android/build_ffmpeg.sh on the android branch).
#
#   build_ffmpeg.sh <ffmpeg source> <work dir> <install prefix>
#
#   ffmpeg source   an extracted FFmpeg release (tested: n9.0.2)
#   work dir        scratch build directory, created if missing
#   install prefix  where include/ and lib/ go
#
# Run it from the devkitPro MSYS2 shell (or any shell where DEVKITPRO points at
# the devkitPro install, in MSYS2 form, e.g. /opt/devkitpro). Needs make, sed,
# awk and friends, and a host C compiler (see HOST_CC below). None of the
# three paths may contain spaces: FFmpeg's configure does not support them.
#
# What is built in, and why (same list as Android):
#   bink, binkaudio_rdft, binkaudio_dct   the game's movies (FMV/*.bik, Bink 1)
#   vorbis, opus, flac, mp3, pcm          replacement sounds from mods
#                                         (iModAudio.cpp; WAV works without FFmpeg)
# LGPL only: no --enable-gpl, no --enable-nonfree.
#
# Differences from Android:
#   --target-os=none   FFmpeg has no Horizon target; devkitPro's own
#                      switch-ffmpeg package patches one in. "none" is enough
#                      for a decoder-only build: newlib supplies the libc.
#   --disable-pthreads none of the built-in decoders use frame or slice
#                      threads, so a single-threaded build loses nothing and
#                      does not depend on libnx's pthread layer.
#   the compile flags are Switch.cmake's (NintendoSwitch.cmake), so the
#   objects match the rest of the .nro (-mtp=soft, local-exec TLS, PIE).

set -e

if [ $# -ne 3 ]; then
    echo "usage: $0 <ffmpeg source> <work dir> <install prefix>" >&2
    exit 2
fi

SRC=$1
WORK=$2
PREFIX=$3

DEVKITPRO=${DEVKITPRO:-/opt/devkitpro}
if [ ! -x "$DEVKITPRO/devkitA64/bin/aarch64-none-elf-gcc" ] &&
   [ ! -x "$DEVKITPRO/devkitA64/bin/aarch64-none-elf-gcc.exe" ]; then
    echo "devkitA64 not found under DEVKITPRO=$DEVKITPRO" >&2
    exit 2
fi
export PATH="$DEVKITPRO/devkitA64/bin:$PATH"

mkdir -p "$WORK"
cd "$WORK"

# A compiler for the build machine. swscale's aarch64 code is generated by a
# small program built and run during the build (libswscale/aarch64/
# ops_asmgen.c), so it has to compile AND link for the host. devkitPro's
# MSYS2 has no host compiler; on Windows the LLVM clang in Program Files works
# without a Visual Studio prompt. Its path has a space, which configure cannot
# take, hence the wrapper.
if [ -z "$HOST_CC" ]; then
    if command -v cc >/dev/null 2>&1; then
        HOST_CC=cc
    elif command -v gcc >/dev/null 2>&1; then
        HOST_CC=gcc
    elif [ -x "/c/Program Files/LLVM/bin/clang.exe" ]; then
        printf '#!/bin/sh\nexec "/c/Program Files/LLVM/bin/clang.exe" "$@"\n' > "$WORK/host-cc"
        chmod +x "$WORK/host-cc"
        HOST_CC="$WORK/host-cc"
    else
        echo "no host C compiler: set HOST_CC" >&2
        exit 2
    fi
fi

# The source and work folders as gcc sees them (on Windows, MSYS2 hands it
# Windows paths). __FILE__, which FFmpeg's assertions carry, then starts at the
# source folder, so tssm.nro does not carry the folders FFmpeg was built in.
gccpath() { if command -v cygpath >/dev/null 2>&1; then cygpath -m "$1"; else printf '%s' "$1"; fi; }
MSRC=$(cd "$SRC" && pwd)
MWORK=$(pwd)
WSRC=$(gccpath "$MSRC")
WWORK=$(gccpath "$MWORK")

NX_ARCH="-march=armv8-a+crc+crypto -mtune=cortex-a57 -mtp=soft -ftls-model=local-exec"
NX_CFLAGS="$NX_ARCH -ffunction-sections -fdata-sections -D__SWITCH__ -fPIE -O2 -I$DEVKITPRO/libnx/include"
NX_CFLAGS="$NX_CFLAGS -ffile-prefix-map=$WSRC/= -ffile-prefix-map=$WWORK/="
NX_LDFLAGS="-specs=$DEVKITPRO/libnx/switch.specs -L$DEVKITPRO/libnx/lib -fPIE $NX_ARCH"

"$SRC/configure" \
    --prefix="$PREFIX" \
    --host-cc="$HOST_CC" \
    --enable-cross-compile --target-os=none --arch=aarch64 --cpu=armv8-a \
    --cross-prefix=aarch64-none-elf- \
    --extra-cflags="$NX_CFLAGS" \
    --extra-ldflags="$NX_LDFLAGS" \
    --extra-libs="-lnx -lm" \
    --enable-static --disable-shared --enable-pic \
    --disable-autodetect --disable-programs --disable-doc --disable-debug \
    --disable-avdevice --disable-avfilter --disable-network \
    --disable-pthreads --disable-runtime-cpudetect \
    --disable-everything \
    --enable-avcodec --enable-avformat --enable-avutil --enable-swscale --enable-swresample \
    --enable-decoder=bink,binkaudio_rdft,binkaudio_dct \
    --enable-decoder=vorbis,opus,flac,mp3,mp3float \
    --enable-decoder=pcm_s16le,pcm_s24le,pcm_s32le,pcm_f32le,pcm_u8 \
    --enable-demuxer=bink,ogg,flac,mp3,wav \
    --enable-parser=vorbis,opus,flac,mpegaudio \
    --enable-protocol=file \
    --enable-neon

# The configure line is compiled in as well (avcodec_configuration()): keep it,
# with the three folders named by their role instead of their paths.
sedesc() { printf '%s' "$1" | sed 's/[][\.*^$|]/\\&/g'; }
sed -i -e "/^#define FFMPEG_CONFIGURATION /{
s|$(sedesc "$PREFIX")|<prefix>|g
s|$(sedesc "$(gccpath "$PREFIX")")|<prefix>|g
s|$(sedesc "$WSRC")|<source>|g
s|$(sedesc "$MSRC")|<source>|g
s|$(sedesc "$WWORK")|<build>|g
s|$(sedesc "$MWORK")|<build>|g
}" config.h
grep '^#define FFMPEG_CONFIGURATION ' config.h

JOBS=${JOBS:-$(getconf _NPROCESSORS_ONLN 2>/dev/null || echo 4)}
make -j"$JOBS"
make install

# The license, where the GUI's About tab reads it (CMakeLists.txt,
# tssm_gui_notice "FFmpeg").
mkdir -p "$PREFIX/share/ffmpeg"
cp "$SRC/COPYING.LGPLv2.1" "$PREFIX/share/ffmpeg/copyright"
