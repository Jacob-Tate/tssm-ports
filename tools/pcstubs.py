#!/usr/bin/env python3
"""The PC port's stub inventory, generated from the source.

Writes src/SB/Core/pc/stubs/STUBS.md. With --check, writes nothing and exits 1
when that file is out of date (run it after adding or implementing a stub).

What counts, all under src/SB/Core/pc:

  * every function whose body calls IPORT_STUB() (iStub.h). Such a function
    does nothing, or the least that keeps the game going, and prints
    "[pcport] not implemented: <name>" the first time it runs, so the run log
    names the stubs a session actually reached;
  * every other function defined in stubs/, listed as implemented, so each SDK
    module's whole PC surface is visible in one place;
  * every function of a module whose header comment calls the whole file a
    STUB (iAsync.cpp): most of those are empty without saying so.

Usage:
    tools/pcstubs.py            rewrite src/SB/Core/pc/stubs/STUBS.md
    tools/pcstubs.py --check    exit 1 if it is stale
    tools/pcstubs.py --print    print the table to stdout as well
"""

import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
PC = ROOT / "src/SB/Core/pc"
OUT = PC / "stubs/STUBS.md"

# Display names, in report order. Anything else is named by its path.
SUBSYSTEMS = [
    ("stubs/dolphin_gx.cpp", "Dolphin SDK: GX"),
    ("stubs/dolphin_vi.cpp", "Dolphin SDK: VI"),
    ("stubs/dolphin_os.cpp", "Dolphin SDK: OS"),
    ("stubs/dolphin_card.cpp", "Dolphin SDK: CARD"),
    ("stubs/bink.cpp", "Bink"),
    ("stubs/fmod.cpp", "FMOD"),
    ("iSnd.cpp", "Sound (iSnd)"),
    ("iAsync.cpp", "Load-screen thread (iAsync)"),
    ("iFMV.cpp", "Movies (iFMV)"),
    ("rw/tssm.cpp", "RenderWare shim (TSSM additions)"),
]

# A definition starts at column 0 with a return type and a name followed by
# '(' and does not end in ';' (a declaration) -- good enough for this layer's
# own files, which clang-format keeps in one shape.
DEF = re.compile(r"^(?![#/ \t{}])(?!(?:return|else|if|for|while|switch|do)\b)"
                 r"[^;=()]*?\b(?P<name>[A-Za-z_~][\w:~]*)\s*\((?P<rest>[^;]*)$")
STUB_CALL = re.compile(r"^\s*IPORT_STUB\(\);")
WHOLE_MODULE = re.compile(r"\bSTUB\b")


def functions(text):
    """(name, line, body_text) for each function defined in the file."""
    lines = text.splitlines()
    out = []
    i = 0
    while i < len(lines):
        m = DEF.match(lines[i])
        if m and m.group("name") not in ("extern",):
            # The body opens at the first '{' at column 0 after the signature.
            j = i
            while j < len(lines) and not lines[j].startswith("{"):
                if lines[j].rstrip().endswith(";"):
                    break
                j += 1
            if j < len(lines) and lines[j].startswith("{"):
                k = j + 1
                while k < len(lines) and not lines[k].startswith("}"):
                    k += 1
                out.append((m.group("name"), i + 1, "\n".join(lines[j:k + 1])))
                i = k + 1
                continue
        i += 1
    return out


def header_comment(text):
    lines = []
    for line in text.splitlines():
        if line.startswith("//"):
            lines.append(line[2:].strip())
        elif lines:
            break
    return lines


def first_sentence(header):
    text = " ".join(l for l in header if l)
    m = re.match(r"(.+?\.)(\s|$)", text)
    return (m.group(1) if m else text)[:240]


def scan():
    records = {}
    for path in sorted(PC.rglob("*.cpp")):
        rel = path.relative_to(PC).as_posix()
        if rel.startswith("rw/tests/"):
            continue
        text = path.read_text(errors="replace")
        header = header_comment(text)
        whole = (not rel.startswith("stubs/") and
                 any(WHOLE_MODULE.search(l) for l in header))
        funcs = functions(text)
        rows = []
        for name, line, body in funcs:
            stub = any(STUB_CALL.match(l) for l in body.splitlines())
            if stub:
                rows.append((name, line, "stub"))
            elif rel.startswith("stubs/"):
                rows.append((name, line, "implemented"))
            elif whole:
                rows.append((name, line, "module stub"))
        if rows:
            records[rel] = {"rows": rows, "about": first_sentence(header), "whole": whole}
    return records


def render(records):
    order = [f for f, _ in SUBSYSTEMS if f in records]
    order += sorted(f for f in records if f not in order)
    names = dict(SUBSYSTEMS)

    total_stub = sum(1 for r in records.values() for row in r["rows"] if row[2] != "implemented")
    total_impl = sum(1 for r in records.values() for row in r["rows"] if row[2] == "implemented")

    out = []
    out.append("# PC stub inventory")
    out.append("")
    out.append("Generated by `tools/pcstubs.py` from the source under `src/SB/Core/pc`; do not edit.")
    out.append("Rerun it after adding or implementing a stub (`--check` says when this file is stale).")
    out.append("")
    out.append("- **stub**: the body calls `IPORT_STUB()` and prints `[pcport] not implemented: <name>` the")
    out.append("  first time it runs, so a run log names the stubs that session reached.")
    out.append("- **module stub**: a function of a module whose header calls the whole file a stub; most of")
    out.append("  these are silent.")
    out.append("- **implemented**: a function in `stubs/` that does its job on PC; listed so each SDK module's")
    out.append("  whole PC surface is in one place.")
    out.append("")
    out.append(f"Totals: {total_stub} stubbed, {total_impl} implemented.")
    out.append("")
    out.append("| Subsystem | File | Stubbed | Implemented |")
    out.append("|---|---|---|---|")
    for f in order:
        rows = records[f]["rows"]
        n_stub = sum(1 for r in rows if r[2] != "implemented")
        n_impl = sum(1 for r in rows if r[2] == "implemented")
        out.append(f"| {names.get(f, f)} | `{f}` | {n_stub} | {n_impl} |")
    for f in order:
        rec = records[f]
        out.append("")
        out.append(f"## {names.get(f, f)}")
        out.append("")
        out.append(f"`src/SB/Core/pc/{f}`: {rec['about']}")
        out.append("")
        for name, line, kind in rec["rows"]:
            out.append(f"- `{name}` ({kind}, line {line})")
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--print", action="store_true")
    args = ap.parse_args()

    text = render(scan())
    if args.print:
        sys.stdout.write(text)
    if args.check:
        current = OUT.read_text() if OUT.exists() else ""
        if current.replace("\r\n", "\n") != text:
            print(f"{OUT.relative_to(ROOT).as_posix()} is out of date -- run tools/pcstubs.py")
            return 1
        print("stub inventory up to date")
        return 0
    OUT.write_text(text, newline="\n")
    print(f"wrote {OUT.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
