#!/bin/sh
# Builds the FFmpeg the Android port links: static libavformat, libavcodec,
# libswscale, libswresample and libavutil for one Android ABI, with only the
# decoders the port uses. docs/ANDROID.md, "Movies".
#
#   build_ffmpeg.sh <ffmpeg source> <work dir> <abi> <install prefix>
#
#   ffmpeg source   an extracted FFmpeg release (tested: n9.0.2)
#   work dir        scratch build directory, created if missing
#   abi             arm64-v8a or armeabi-v7a
#   install prefix  where include/ and lib/ go (gradle -Ptssm.ffmpeg=<dir>
#                   expects <dir>/<abi>/include and <dir>/<abi>/lib)
#
# Needs a POSIX shell with make, sed, awk and friends (Linux, macOS, or MSYS2
# on Windows) and ANDROID_NDK_HOME pointing at NDK r28c. None of the four
# paths may contain spaces: FFmpeg's configure does not support them.
#
# What is built in, and why:
#   bink, binkaudio_rdft, binkaudio_dct   the game's movies (FMV/*.bik, Bink 1)
#   vorbis, opus, flac, mp3, pcm          replacement sounds from mods
#                                         (iModAudio.cpp; WAV works without FFmpeg)
# LGPL only: no --enable-gpl, no --enable-nonfree.

set -e

if [ $# -ne 4 ]; then
    echo "usage: $0 <ffmpeg source> <work dir> <abi> <install prefix>" >&2
    exit 2
fi

SRC=$1
WORK=$2
ABI=$3
PREFIX=$4
API=${ANDROID_API:-24}

if [ -z "$ANDROID_NDK_HOME" ]; then
    echo "ANDROID_NDK_HOME is not set" >&2
    exit 2
fi

case "$(uname -s)" in
    Linux*) HOST=linux-x86_64; EXE= ;;
    Darwin*) HOST=darwin-x86_64; EXE= ;;
    *) HOST=windows-x86_64; EXE=.exe ;;
esac
TC=$ANDROID_NDK_HOME/toolchains/llvm/prebuilt/$HOST/bin

case "$ABI" in
    arm64-v8a)
        ARCH=aarch64; CPU=armv8-a; TRIPLE=aarch64-linux-android
        ABI_FLAGS=
        ABI_CONFIG="--enable-neon"
        ;;
    armeabi-v7a)
        ARCH=arm; CPU=armv7-a; TRIPLE=armv7a-linux-androideabi
        ABI_FLAGS="-mfloat-abi=softfp -mfpu=neon -mthumb"
        ABI_CONFIG="--enable-neon --enable-thumb"
        ;;
    *)
        echo "unknown ABI '$ABI' (arm64-v8a or armeabi-v7a)" >&2
        exit 2
        ;;
esac

mkdir -p "$WORK"
cd "$WORK"

# A compiler for the build machine. swscale's aarch64 code is generated by a
# small program built and run during the build (libswscale/aarch64/
# ops_asmgen.c), so it has to compile AND link for the host. (--disable-
# unstable would avoid that program, but n9.0.2's swscale does not link
# without the unstable code.) MSYS2 has no compiler by default; on Windows the
# LLVM clang in Program Files works without a Visual Studio prompt. Its path
# has a space, which configure cannot take, hence the wrapper.
if [ -z "$HOST_CC" ]; then
    if command -v cc >/dev/null 2>&1; then
        HOST_CC=cc
    elif command -v gcc >/dev/null 2>&1; then
        HOST_CC=gcc
    elif [ -x "/c/Program Files/LLVM/bin/clang.exe" ]; then
        printf '#!/bin/sh\nexec "/c/Program Files/LLVM/bin/clang.exe" "$@"\n' > "$WORK/host-cc"
        chmod +x "$WORK/host-cc"
        HOST_CC="$WORK/host-cc"
    else
        echo "no host C compiler: set HOST_CC" >&2
        exit 2
    fi
fi

"$SRC/configure" \
    --prefix="$PREFIX" \
    --host-cc="$HOST_CC" \
    --enable-cross-compile --target-os=android --arch=$ARCH --cpu=$CPU \
    --cc="$TC/clang$EXE" --ar="$TC/llvm-ar$EXE" --nm="$TC/llvm-nm$EXE" \
    --ranlib="$TC/llvm-ranlib$EXE" --strip="$TC/llvm-strip$EXE" \
    --extra-cflags="--target=$TRIPLE$API $ABI_FLAGS -fPIC -O2" \
    --extra-ldflags="--target=$TRIPLE$API" \
    --enable-static --disable-shared --enable-pic \
    --disable-autodetect --disable-programs --disable-doc --disable-debug \
    --disable-avdevice --disable-avfilter --disable-network \
    --disable-everything \
    --enable-avcodec --enable-avformat --enable-avutil --enable-swscale --enable-swresample \
    --enable-decoder=bink,binkaudio_rdft,binkaudio_dct \
    --enable-decoder=vorbis,opus,flac,mp3,mp3float \
    --enable-decoder=pcm_s16le,pcm_s24le,pcm_s32le,pcm_f32le,pcm_u8 \
    --enable-demuxer=bink,ogg,flac,mp3,wav \
    --enable-parser=vorbis,opus,flac,mpegaudio \
    --enable-protocol=file \
    $ABI_CONFIG

JOBS=${JOBS:-$(getconf _NPROCESSORS_ONLN 2>/dev/null || echo 4)}
make -j"$JOBS"
make install

# The license, where the GUI's About tab reads it (CMakeLists.txt,
# tssm_gui_notice "FFmpeg").
mkdir -p "$PREFIX/share/ffmpeg"
cp "$SRC/COPYING.LGPLv2.1" "$PREFIX/share/ffmpeg/copyright"
